import fs from 'fs';
import path from 'path';
import { execFile } from 'child_process';
import { BrowserWindow } from 'electron';
import { downloadFile } from './downloader';

export interface NeoForgeLaunchDetails {
  versionId: string;
  mainClass: string;
  jvmArgs: string[];
  gameArgs: string[];
  libraries: string[];
}

export function mavenCoordinateToPath(coord: string): string {
  const parts = coord.split(':');
  if (parts.length < 3) return coord;
  const group = parts[0].replace(/\./g, '/');
  const name = parts[1];
  const versionWithExt = parts[2];
  let version = versionWithExt;
  let ext = 'jar';
  if (versionWithExt.includes('@')) {
    const split = versionWithExt.split('@');
    version = split[0];
    ext = split[1];
  }
  const classifier = parts[3] ? `-${parts[3]}` : '';
  return `${group}/${name}/${version}/${name}-${version}${classifier}.${ext}`;
}

export async function ensureNeoForge(
  mcVersion: string = '1.21.1',
  loaderVersion: string = '21.1.65',
  gameDir: string,
  javaPath: string,
  win: BrowserWindow | null
): Promise<NeoForgeLaunchDetails> {
  const versionId = `${mcVersion}-neoforge-${loaderVersion}`;
  const neoforgeVersionDir = path.join(gameDir, 'versions', versionId);
  const versionJsonPath = path.join(neoforgeVersionDir, `${versionId}.json`);

  const readProfileDetails = (): NeoForgeLaunchDetails => {
    if (fs.existsSync(versionJsonPath)) {
      try {
        const data = JSON.parse(fs.readFileSync(versionJsonPath, 'utf8'));
        const mainClass = data.mainClass || 'cpw.mods.bootstraplauncher.BootstrapLauncher';
        const librariesDir = path.join(gameDir, 'libraries');

        const libraries: string[] = [];
        if (Array.isArray(data.libraries)) {
          for (const lib of data.libraries) {
            let relPath = '';
            if (lib.downloads?.artifact?.path) {
              relPath = lib.downloads.artifact.path;
            } else if (typeof lib.name === 'string') {
              relPath = mavenCoordinateToPath(lib.name);
            }
            if (relPath) {
              const fullLibPath = path.join(librariesDir, relPath);
              if (fs.existsSync(fullLibPath)) {
                libraries.push(fullLibPath);
              }
            }
          }
        }

        const jvmArgs: string[] = [];
        const gameArgs: string[] = [];

        // Parse arguments block if present (standard in NeoForge 1.21.1)
        if (data.arguments) {
          if (Array.isArray(data.arguments.jvm)) {
            for (const arg of data.arguments.jvm) {
              if (typeof arg === 'string') {
                const resolved = arg
                  .replace(/\${library_directory}/g, librariesDir)
                  .replace(/\${classpath_separator}/g, process.platform === 'win32' ? ';' : ':')
                  .replace(/\${version_name}/g, versionId);
                jvmArgs.push(resolved);
              }
            }
          }
          if (Array.isArray(data.arguments.game)) {
            for (const arg of data.arguments.game) {
              if (typeof arg === 'string') {
                gameArgs.push(arg);
              }
            }
          }
        }

        // Check for args.txt file generated by NeoForge installer in libraries
        const argsFileName = process.platform === 'win32' ? 'win_args.txt' : 'unix_args.txt';
        const neoArgsPath = path.join(
          librariesDir,
          'net',
          'neoforged',
          'neoforge',
          loaderVersion,
          argsFileName
        );
        if (fs.existsSync(neoArgsPath)) {
          jvmArgs.push(`@${neoArgsPath}`);
        }

        return { versionId, mainClass, jvmArgs, gameArgs, libraries };
      } catch (err) {
        console.warn('Failed to parse NeoForge version.json, falling back to defaults:', err);
      }
    }

    return {
      versionId,
      mainClass: 'cpw.mods.bootstraplauncher.BootstrapLauncher',
      jvmArgs: [],
      gameArgs: [],
      libraries: [],
    };
  };

  if (fs.existsSync(versionJsonPath)) {
    return readProfileDetails();
  }

  // Download NeoForge Installer
  const installerUrl = `https://maven.neoforged.net/releases/net/neoforged/neoforge/${loaderVersion}/neoforge-${loaderVersion}-installer.jar`;
  const installerPath = path.join(gameDir, 'temp', `neoforge-${loaderVersion}-installer.jar`);

  if (win && !win.isDestroyed()) {
    win.webContents.send('download-progress', {
      stage: 'neoforge',
      stageLabel: `Загрузка установщика NeoForge ${loaderVersion} для Minecraft ${mcVersion}...`,
      progressPercent: 50,
    });
  }

  await downloadFile(installerUrl, installerPath);

  if (win && !win.isDestroyed()) {
    win.webContents.send('download-progress', {
      stage: 'neoforge',
      stageLabel: `Установка профиля NeoForge ${loaderVersion}...`,
      progressPercent: 75,
    });
  }

  await new Promise<void>((resolve, reject) => {
    execFile(
      javaPath || 'java',
      ['-jar', installerPath, '--installClient', gameDir],
      { cwd: gameDir, maxBuffer: 10 * 1024 * 1024 },
      (error, _stdout, stderr) => error ? reject(new Error(`NeoForge не установлен: ${stderr || error.message}`)) : resolve()
    );
  });

  if (!fs.existsSync(versionJsonPath)) throw new Error('Установщик NeoForge не создал профиль игры');

  return readProfileDetails();
}
