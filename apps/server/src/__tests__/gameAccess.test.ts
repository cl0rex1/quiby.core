import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { generateKeyPairSync } from 'node:crypto';
import express from 'express';
import jwt from 'jsonwebtoken';
import { MINIMUM_LAUNCHER_VERSION } from '@quiby/shared';

test('Minecraft policy is independent, persistent, authenticated and rechecks previously issued tickets', async () => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'quiby-game-access-'));
  process.env.DB_PATH = path.join(directory, 'test.sqlite'); process.env.STORAGE_PATH = directory;
  const { config } = await import('../config'); config.adminApiKey = 'game-access-test-key';
  const { initDatabase, dbRun, closeDatabase } = await import('../models/db'); await initDatabase();
  const { requireAuth } = await import('../middleware/auth');
  const { getLauncherAccess, setLauncherAccess } = await import('../services/launcherAccess');
  const { getGameAccess } = await import('../services/gameAccess');
  const app = express(); app.use(express.json());
  app.use('/api/control', (await import('../routes/control')).default);
  app.use('/api/game', (await import('../routes/game')).default);
  app.get('/browse', requireAuth, (_req, res) => res.sendStatus(204));
  const server = app.listen(0, '127.0.0.1'); await new Promise<void>(resolve => server.once('listening', resolve));
  const base = 'http://127.0.0.1:' + (server.address() as { port: number }).port;
  const id = '123456789012345678', uuid = 'f4606112-bd19-394a-bd0b-0b7f6f6a5001';
  const token = jwt.sign({ discordId: id, mcUsername: 'Tester', authMethod: 'discord' }, config.jwtSecret);
  const headers = { 'Content-Type': 'application/json', 'x-quiby-launcher-version': MINIMUM_LAUNCHER_VERSION, 'X-Quiby-Control': '1' };
  const player = { ...headers, Authorization: 'Bearer ' + token };
  const publicKey = generateKeyPairSync('ed25519').publicKey.export({ type: 'spki', format: 'der' }).toString('base64');
  const issue = () => fetch(base + '/api/game/join-ticket', { method: 'POST', headers: player, body: JSON.stringify({ publicKey }) });
  try {
    await dbRun('INSERT INTO users(discord_id,discord_username,mc_username,uuid) VALUES(?,?,?,?)', [id, 'Tester', 'Tester', uuid]);
    assert.equal((await getGameAccess()).closed, false);
    const ticket = (await (await issue()).json()).ticket;
    const verify = () => fetch(base + '/api/game/verify-join-ticket', { method: 'POST', headers, body: JSON.stringify({ ticket, username: 'Tester', uuid }) });
    assert.equal((await verify()).status, 200);
    assert.equal((await fetch(base + '/api/control/minecraft-access', { method: 'PUT', headers, body: '{"closed":true}' })).status, 401);
    const login = await fetch(base + '/api/control/login', { method: 'POST', headers, body: JSON.stringify({ key: config.adminApiKey }) });
    const admin = { ...headers, Cookie: login.headers.get('set-cookie')!.split(';')[0] };
    const change = (body: object, overrides = {}) => fetch(base + '/api/control/minecraft-access', { method: 'PUT', headers: { ...admin, ...overrides }, body: JSON.stringify(body) });
    const updatePlayer = (body: object) => fetch(base + '/api/control/players/' + id, { method: 'PATCH', headers: admin, body: JSON.stringify(body) });
    assert.equal((await change({ closed: true }, { Origin: 'https://evil.example' })).status, 403);
    assert.equal((await change({ closed: 'true' })).status, 400);
    assert.equal((await change({ closed: true, message: 'x'.repeat(501) })).status, 400);
    assert.equal((await change({ closed: true, message: 'Готовим мир' })).status, 200);
    await initDatabase();
    assert.equal((await getGameAccess()).closed, true);
    assert.equal((await getLauncherAccess()).closed, false);
    assert.equal((await fetch(base + '/browse', { headers: player })).status, 204, 'Launcher browsing is unaffected');
    const denied = await issue(); assert.equal(denied.status, 503); assert.equal((await denied.json()).error, 'Готовим мир');
    assert.equal((await verify()).status, 403, 'Previously issued ticket cannot bypass closure');
    assert.equal((await fetch(base + '/api/game/playtime', { method: 'PUT', headers: player, body: JSON.stringify({ deviceId: uuid, totalSeconds: 42 }) })).status, 200);
    assert.equal((await updatePlayer({ minecraftExempt: true })).status, 200);
    assert.equal((await issue()).status, 200); assert.equal((await verify()).status, 200);
    const access = async (extra: Record<string, string> = {}) => (await fetch(base + '/api/game/access', { headers: extra })).json();
    assert.equal((await access(player)).closed, false);
    assert.equal((await access({ 'x-discord-id': id })).closed, true);
    assert.equal((await access({ Authorization: 'Bearer ' + token + 'tampered' })).closed, true);
    const binding = jwt.sign({ discordId: id, mcUsername: 'Tester', purpose: 'mc_binding' }, config.jwtSecret);
    assert.equal((await access({ Authorization: 'Bearer ' + binding })).closed, true);
    assert.equal((await updatePlayer({ launcherExempt: true })).status, 200);
    await setLauncherAccess(true, 'Launcher maintenance');
    assert.equal((await issue()).status, 200, 'Both exceptions are independent');
    assert.equal((await updatePlayer({ minecraftBlocked: true })).status, 200);
    assert.equal((await issue()).status, 403);
    assert.equal((await fetch(base + '/browse', { headers: player })).status, 204);
    assert.equal((await updatePlayer({ minecraftExempt: true })).status, 400);
    assert.equal((await updatePlayer({ minecraftBlocked: false })).status, 200);
    assert.equal((await issue()).status, 503, 'Personal block revokes the Minecraft exception');
    assert.equal((await updatePlayer({ minecraftExempt: true })).status, 200);
    assert.equal((await updatePlayer({ allowed: false })).status, 200);
    assert.equal((await updatePlayer({ minecraftExempt: true })).status, 400);
    assert.equal((await updatePlayer({ allowed: true })).status, 200);
    assert.equal((await issue()).status, 503, 'Personal whitelist ban revokes both exceptions');
    await setLauncherAccess(false, '');
    assert.equal((await change({ closed: false, message: '' })).status, 200);
    assert.equal((await issue()).status, 200); assert.equal((await verify()).status, 200);
    const audit = await (await fetch(base + '/api/control/audit', { headers: admin })).json();
    assert.ok(audit.items.some((row: any) => row.action === 'minecraft:close'));
    assert.ok(audit.items.some((row: any) => row.action === 'minecraft:player-block'));
  } finally {
    await new Promise<void>(resolve => server.close(() => resolve())); await closeDatabase(); await fs.rm(directory, { recursive: true, force: true });
  }
});
